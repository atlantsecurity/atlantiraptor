// "AI triage" button and dialog. It shows exactly how much data will be
// sent and a preview before anything leaves the server, runs the request
// server-side (Server.AI.Triage, keys stay in secrets), and renders the
// answer as plain text: model output can echo attacker-controlled data.
import { useEffect, useState } from 'react';
import { toast } from 'sonner';
import { Copy, NotebookPen, Send, Sparkles } from 'lucide-react';
import { runServerArtifact } from '../../lib/serverRun';
import { useServerMetadata } from '../../lib/queries';
import { Button, Dialog, Skeleton } from '../../ui/primitives';

export const AI_ARTIFACT = 'Server.AI.Triage';

interface Props {
  label?: string;
  task: string;
  getContext: () => Promise<string>;
  onSaveNote?: (text: string) => Promise<unknown>;
  size?: 'sm' | 'md';
}

export function AiTriageButton({ label = 'AI triage', size = 'sm', ...rest }: Props) {
  const [open, setOpen] = useState(false);
  return <>
    <Button size={size} variant="secondary" icon={<Sparkles className="tw:size-3.5" />} onClick={() => setOpen(true)}>{label}</Button>
    {open && <AiTriageDialog {...rest} onClose={() => setOpen(false)} />}
  </>;
}

function AiTriageDialog({ task, getContext, onSaveNote, onClose }: Props & { onClose: () => void }) {
  const meta = useServerMetadata();
  const [context, setContext] = useState<string | null>(null);
  const [loadError, setLoadError] = useState('');
  const [busy, setBusy] = useState(false);
  const [answer, setAnswer] = useState<{ text: string; provider: string; model: string } | null>(null);

  useEffect(() => {
    let live = true;
    getContext().then(c => { if (live) setContext(c); }, e => { if (live) setLoadError((e as Error).message); });
    return () => { live = false; };
  }, []); // eslint-disable-line react-hooks/exhaustive-deps

  const provider = meta.data?.atl_ai_provider;
  const model = meta.data?.atl_ai_model;
  const target = provider ? `${provider}${model ? ` (${model})` : ''}` : 'the AI provider configured on the server';

  const send = async () => {
    if (!context) return;
    setBusy(true);
    try {
      const r = await runServerArtifact(AI_ARTIFACT, { Task: task, Context: context }, { timeoutMs: 240_000 });
      const row = r.rows[0] ?? {};
      const status = Number(row.Status ?? 0);
      const text = String(row.Summary ?? '') || 'No answer.';
      if (!(status >= 200 && status < 300)) {
        toast.error(text);
        return;
      }
      setAnswer({ text, provider: String(row.Provider ?? ''), model: String(row.Model ?? '') });
    } catch (e) {
      toast.error((e as Error).message);
    } finally {
      setBusy(false);
    }
  };

  return (
    <Dialog open onOpenChange={v => !v && onClose()} width={760} title="AI triage"
      description={answer ? `Answer from ${answer.provider} ${answer.model}. AI can be wrong: check findings against the data.` : `Sends the data below to ${target} for a triage summary.`}
      footer={answer ? <>
        <Button variant="ghost" icon={<Copy className="tw:size-3.5" />} onClick={() => navigator.clipboard.writeText(answer.text).then(() => toast.success('Copied'))}>Copy</Button>
        {onSaveNote && <Button variant="secondary" icon={<NotebookPen className="tw:size-3.5" />}
          onClick={() => onSaveNote(`[AI-generated by ${answer.provider} ${answer.model} – unverified, may be wrong or influenced by collected data]\n${answer.text}`).then(() => { toast.success('Saved to the case'); onClose(); }, e => toast.error((e as Error).message))}>Save as case note</Button>}
        <Button variant="primary" onClick={onClose}>Done</Button>
      </> : <>
        <Button variant="ghost" onClick={onClose}>Cancel</Button>
        <Button variant="primary" icon={<Send className="tw:size-3.5" />} loading={busy} disabled={!context} onClick={send}>Send to AI</Button>
      </>}>
      {answer ? (
        <pre className="tw:whitespace-pre-wrap tw:break-words tw:text-[13px] tw:font-sans tw:max-h-[60vh] tw:overflow-auto">{answer.text}</pre>
      ) : loadError ? (
        <div className="tw:text-xs tw:text-bad">Could not gather the data: {loadError}</div>
      ) : context === null ? <Skeleton className="tw:h-40" /> : (
        <div className="tw:space-y-2 tw:text-xs">
          <div className="tw:text-muted">
            Task: <b className="tw:text-fg">{task}</b> · {context.length.toLocaleString()} characters will leave the server.
          </div>
          <pre className="tw:whitespace-pre-wrap tw:break-all tw:font-mono tw:text-[11px] tw:max-h-72 tw:overflow-auto tw:rounded-md tw:border tw:border-line tw:bg-canvas/50 tw:p-2">
            {context.slice(0, 4000)}{context.length > 4000 ? '\n…' : ''}
          </pre>
          {busy && <div className="tw:text-muted">Waiting for the model. This can take a minute.</div>}
        </div>
      )}
    </Dialog>
  );
}

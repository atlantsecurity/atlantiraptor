<#
.SYNOPSIS
    Installs the Atlantiraptor agent and connects it to your Atlantiraptor server.

.DESCRIPTION
    Generated by the Atlantiraptor console (Clients > Deploy a client) on {{.Generated}}
    for org "{{.OrgName}}". Server: {{.ServerURLs}}

    This script contains the server's client configuration: the server address, the CA
    certificate the agent trusts and the org's enrollment nonce. Anyone with this file can
    enroll a computer to your server, so share it only with the people who deploy agents.

    It installs the agent the same way as the Atlantiraptor MSI: the Windows service
    "Atlantiraptor", running as LocalSystem, in
    C:\Program Files\Atlant Security\Atlantiraptor, readable only by SYSTEM and Administrators.

    The program is Atlantiraptor.exe next to this script, the file given with -Binary, or else
    downloaded from {{.DownloadURL}}
    It is installed only if it is Authenticode-signed by Atlant Security EOOD and Windows
    trusts the signature.

    Run it as an administrator, or as SYSTEM from Intune, Group Policy or SCCM. Running it
    again on a computer that already has the agent changes nothing; -Reinstall replaces it.
    Exit code 0 means the agent is installed and running.

.PARAMETER Binary
    Install this Atlantiraptor.exe instead of downloading one.

.PARAMETER Reinstall
    Replace an agent that is already installed (the computer keeps its client ID).

.PARAMETER Uninstall
    Remove the agent, whether it was installed by this script or by the MSI.

.EXAMPLE
    powershell.exe -NoProfile -ExecutionPolicy Bypass -File .\Install-Atlantiraptor.ps1

.EXAMPLE
    powershell.exe -NoProfile -ExecutionPolicy Bypass -File .\Install-Atlantiraptor.ps1 -Uninstall
#>
[CmdletBinding()]
param(
    [string]$Binary,
    [switch]$Reinstall,
    [switch]$Uninstall
)

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

$ServiceName = 'Atlantiraptor'
$Signer      = 'Atlant Security EOOD'
$DownloadUrl = '{{.DownloadURL}}'
$ConfigB64   = '{{.ConfigB64}}'

# The 64-bit Program Files folder, also from 32-bit PowerShell (Intune can run scripts that way).
$ProgramFiles64 = if ($env:ProgramW6432) { $env:ProgramW6432 } else { $env:ProgramFiles }
$InstallDir = Join-Path $ProgramFiles64 'Atlant Security\Atlantiraptor'
$Exe        = Join-Path $InstallDir 'Atlantiraptor.exe'
$Config     = Join-Path $InstallDir 'client.config.yaml'

$principal = New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())
if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    throw 'Run this script as an administrator (right-click PowerShell > Run as administrator).'
}
if (-not [Environment]::Is64BitOperatingSystem) {
    throw 'Atlantiraptor needs 64-bit Windows.'
}

function Remove-AtlantiraptorAgent {
    $uninstallKeys = 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall',
                     'HKLM:\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall'
    $msi = Get-ChildItem $uninstallKeys -ErrorAction SilentlyContinue |
        Get-ItemProperty -ErrorAction SilentlyContinue |
        Where-Object { $_.DisplayName -eq 'Atlantiraptor' -and $_.WindowsInstaller -eq 1 } |
        Select-Object -First 1
    if ($msi) {
        Write-Output "Uninstalling the Atlantiraptor MSI $($msi.PSChildName)"
        $p = Start-Process msiexec.exe -ArgumentList "/x $($msi.PSChildName) /qn /norestart" -Wait -PassThru
        if ($p.ExitCode -ne 0 -and $p.ExitCode -ne 3010) { throw "msiexec /x failed with exit code $($p.ExitCode)." }
        return
    }

    $svc = Get-Service -Name $ServiceName -ErrorAction SilentlyContinue
    if ($svc) {
        if ($svc.Status -ne 'Stopped') { Stop-Service -Name $ServiceName -Force }
        & sc.exe delete $ServiceName | Out-Null
    }
    # The process can hold its files for a moment after the service stops.
    for ($i = 0; $i -lt 10 -and (Test-Path $InstallDir); $i++) {
        try { Remove-Item -LiteralPath $InstallDir -Recurse -Force } catch { Start-Sleep -Seconds 2 }
    }
    if (Test-Path $InstallDir) { throw "Could not remove $InstallDir." }
}

if ($Uninstall) {
    Remove-AtlantiraptorAgent
    Write-Output 'Atlantiraptor is uninstalled.'
    return
}

$existing = Get-Service -Name $ServiceName -ErrorAction SilentlyContinue
if ($existing -and -not $Reinstall) {
    if ($existing.Status -ne 'Running') { Start-Service -Name $ServiceName }
    Write-Output 'Atlantiraptor is already installed and running. Use -Reinstall to replace it.'
    return
}

$work = Join-Path ([IO.Path]::GetTempPath()) ('atlantiraptor-' + [guid]::NewGuid())
New-Item -ItemType Directory -Path $work | Out-Null
try {
    if (-not $Binary -and $PSScriptRoot -and (Test-Path (Join-Path $PSScriptRoot 'Atlantiraptor.exe'))) {
        $Binary = Join-Path $PSScriptRoot 'Atlantiraptor.exe'
    }
    if ($Binary) {
        $source = (Resolve-Path -LiteralPath $Binary).Path
    } else {
        [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
        $source = Join-Path $work 'Atlantiraptor.exe'
        Write-Output "Downloading $DownloadUrl"
        Invoke-WebRequest -Uri $DownloadUrl -OutFile $source -UseBasicParsing
    }

    $sig = Get-AuthenticodeSignature -FilePath $source
    $subject = if ($sig.SignerCertificate) { $sig.SignerCertificate.Subject } else { '' }
    if ($sig.Status -ne 'Valid' -or $subject -notmatch "(^|, )O=$([regex]::Escape($Signer))(,|$)") {
        throw "Refusing to install ${source}: signature status '$($sig.Status)', signer '$subject'. It must be validly signed by $Signer."
    }

    if ($existing) { Remove-AtlantiraptorAgent }

    New-Item -ItemType Directory -Path $InstallDir -Force | Out-Null
    # Only SYSTEM and Administrators, like the MSI.
    & icacls.exe $InstallDir /inheritance:r /grant:r '*S-1-5-18:(OI)(CI)F' '*S-1-5-32-544:(OI)(CI)F' | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "icacls failed with exit code $LASTEXITCODE." }
    New-Item -ItemType Directory -Path (Join-Path $InstallDir 'Tools') -Force | Out-Null

    Copy-Item -LiteralPath $source -Destination $Exe -Force
    [IO.File]::WriteAllBytes($Config, [Convert]::FromBase64String($ConfigB64))

    New-Service -Name $ServiceName -DisplayName 'Atlantiraptor' `
        -Description 'Atlantiraptor endpoint agent by Atlant Security' `
        -BinaryPathName "`"$Exe`" --config `"$Config`" service run" `
        -StartupType Automatic | Out-Null
    & sc.exe failure $ServiceName reset= 86400 actions= restart/30000/restart/30000/restart/30000 | Out-Null
    Start-Service -Name $ServiceName

    $svc = Get-Service -Name $ServiceName
    $svc.WaitForStatus('Running', [TimeSpan]::FromSeconds(30))
    Write-Output "Atlantiraptor is installed and running. The computer appears in the console under Clients within a minute."
}
finally {
    Remove-Item -LiteralPath $work -Recurse -Force -ErrorAction SilentlyContinue
}
